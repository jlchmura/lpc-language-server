import * as lpc from "./_namespaces/lpc.js";
import { createTestLanguageService } from "./harness.js";

/**
 * Parses `text` and returns its syntactic diagnostics as readable strings (raw
 * diagnostics hold the source file, which Jest cannot serialize when an assertion
 * fails) plus each function declaration's name and parameter count.
 */
function parseFunctions(text: string) {
    const { ls, fileName } = createTestLanguageService({ "test.c": text }, {
        driverType: lpc.LanguageVariant.LDMud,
    });
    const source = ls.getProgram()!.getSourceFile(fileName)!;
    const diagnostics = ls.getSyntacticDiagnostics(fileName).map((d) =>
        `${d.code}: ${lpc.flattenDiagnosticMessageText(d.messageText, "\n")}`
    );
    const functions = source.statements
        .filter(lpc.isFunctionDeclaration)
        .map((fn) => [fn.name?.text, fn.parameters.length]);
    return { diagnostics, functions };
}

it("parses a function declaration generated by a parameterized macro", () => {
    const { diagnostics, functions } = parseFunctions(`#define TEST(suite, name) void name(object test)
TEST(Party, FrontRow) {}
TEST(Party, Combat) {}
void ordinary() {}
`);

    expect(diagnostics).toEqual([]);
    expect(functions).toEqual([
        ["FrontRow", 1],
        ["Combat", 1],
        ["ordinary", 0],
    ]);
});

// Looking ahead for the `(` after a function name that is the last token of a macro
// stream steps out of that stream. Each case ends a different kind of stream there.
it.each([
    {
        title: "an object-like macro",
        text: `#define FN foo
void FN(object x) {}
`,
    },
    {
        title: "a macro body that ends with the name",
        text: `#define DECL(name) void name
DECL(foo)(object x) {}
`,
    },
    {
        title: "a macro whose multi-token argument precedes the name",
        text: `#define DECL(type, name) type name(object x)
DECL(int *, foo) { return 0; }
`,
    },
    {
        title: "a macro expanded inside another macro",
        text: `#define NAME(n) n
#define DECL(n) void NAME(n)(object x)
DECL(foo) {}
`,
    },
])("parses a function named by $title", ({ text }) => {
    const { diagnostics, functions } = parseFunctions(text + "void ordinary() {}\n");

    expect(diagnostics).toEqual([]);
    expect(functions).toEqual([
        ["foo", 1],
        ["ordinary", 0],
    ]);
});

it("finds a definition from the body of a macro-generated function before another expansion", () => {
    const text = `#define TEST(suite, name) void name(object test)
private void helper() {}

TEST(Party, First) {
    helper();
}

TEST(Party, Second) {}
`;
    const { ls, fileName } = createTestLanguageService({ "test.c": text }, {
        driverType: lpc.LanguageVariant.LDMud,
    });

    const definitions = ls.getDefinitionAtPosition(fileName, text.lastIndexOf("helper"));
    expect(definitions?.map(({ fileName, textSpan }) => [fileName, textSpan.start])).toEqual([
        [fileName, text.indexOf("helper")],
    ]);
});
