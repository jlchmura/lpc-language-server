import * as lpc from "./_namespaces/lpc.js";
import { createTestLanguageService } from "./harness.js";

it("parses a function declaration generated by a parameterized macro", () => {
    const { ls, fileName } = createTestLanguageService({
        "test.c": `#define TEST(suite, name) void name(object test)
TEST(Party, FrontRow) {}
TEST(Party, Combat) {}
void ordinary() {}
`,
    }, { driverType: lpc.LanguageVariant.LDMud });
    const source = ls.getProgram()!.getSourceFile(fileName)!;

    expect(ls.getSyntacticDiagnostics(fileName)).toEqual([]);
    const functions = source.statements.filter(lpc.isFunctionDeclaration);
    expect(functions.map((fn) => [fn.name?.text, fn.parameters.length])).toEqual([
        ["FrontRow", 1],
        ["Combat", 1],
        ["ordinary", 0],
    ]);
});

it("finds a definition from the body of a macro-generated function before another expansion", () => {
    const text = `#define TEST(suite, name) void name(object test)
private void helper() {}

TEST(Party, First) {
    helper();
}

TEST(Party, Second) {}
`;
    const { ls, fileName } = createTestLanguageService({ "test.c": text }, {
        driverType: lpc.LanguageVariant.LDMud,
    });

    const definitions = ls.getDefinitionAtPosition(fileName, text.lastIndexOf("helper"));
    expect(definitions?.map(({ fileName, textSpan }) => [fileName, textSpan.start])).toEqual([
        [fileName, text.indexOf("helper")],
    ]);
});
