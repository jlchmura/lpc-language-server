import * as lpc from "./_namespaces/lpc.js";
import { createTestLanguageService } from "./harness.js";

// The scanner reads a function-like macro's arguments as soon as it meets the macro's
// name, in the calling stream. A node that ends just before the call must still end at
// its own last token -- otherwise it covers the call's name and arguments, and lookups
// on the call land in that node and find nothing.

const TEST = `#define TEST(suite, name) void name(object test)\n`;

function load(text: string) {
    const { ls, fileName } = createTestLanguageService({ "test.c": text }, {
        driverType: lpc.LanguageVariant.LDMud,
    });
    const source = ls.getProgram()!.getSourceFile(fileName)!;
    return { ls, fileName, source };
}

function textOf(text: string, node: lpc.Node) {
    return text.slice(node.pos, node.end).trim();
}

describe("a node followed by a macro call", () => {
    it.each([
        { title: "a variable statement", code: `int counter;` },
        { title: "an inherit", code: `inherit "/std/thing";` },
        { title: "a function prototype", code: `void proto();` },
        { title: "a function", code: `void ordinary() {\n    int x;\n}` },
        { title: "a function named by a macro", code: `#define FN named\nvoid FN() {\n    int x;\n}`, last: `void FN() {\n    int x;\n}` },
        { title: "a function whose body is a macro", code: `#define BODY { int y; }\nvoid a() BODY`, last: `void a() BODY` },
        { title: "a function generated by the same macro", code: `TEST(Party, First) {\n    int x;\n}` },
    ])("ends $title before the call", ({ code, last }) => {
        const text = `${TEST}${code}\nTEST(Party, Next) {}\n`;
        const { ls, fileName, source } = load(text);
        const statements = source.statements.filter((s) => s.kind !== lpc.SyntaxKind.DefineDirective);
        const call = text.lastIndexOf("TEST");

        expect(statements.map((s) => textOf(text, s))).toEqual([last ?? code, "TEST(Party, Next) {}"]);
        expect(ls.getDefinitionAtPosition(fileName, call + 1)?.map(({ name, textSpan }) => [name, textSpan.start])).toEqual([
            ["TEST", text.indexOf("TEST")],
        ]);
    });

    it("ends a statement before a call whose macro starts with another macro call", () => {
        const text = `#define INNER(n) void n
#define OUTER(n) INNER(n)(object t)
int counter;
OUTER(foo) {}
`;
        const { source } = load(text);
        const statements = source.statements.filter((s) => s.kind !== lpc.SyntaxKind.DefineDirective);

        expect(statements.map((s) => textOf(text, s))).toEqual(["int counter;", "OUTER(foo) {}"]);
    });
});

describe("a node that ends inside a macro's text", () => {
    it("covers the whole macro call", () => {
        const text = `#define PLUS_ONE(x) x + 1\nint y = 3 * PLUS_ONE(2);\n`;
        const { source } = load(text);
        const sum = (source.statements[1] as lpc.VariableStatement).declarationList.declarations[0].initializer as lpc.BinaryExpression;
        const product = sum.left as lpc.BinaryExpression;

        // `3 * PLUS_ONE(2)` parses as `(3 * 2) + 1`: the product ends at the expanded `2`.
        expect(textOf(text, sum)).toBe("3 * PLUS_ONE(2)");
        expect(textOf(text, product)).toBe("3 * PLUS_ONE(2)");
    });
});
